// Dev tool: prints the MySQL DDL for prisma/schema.prisma in the same shape Prisma Migrate writes.
// Used to create prisma/migrations/<name>/migration.sql where Prisma's schema-engine binary
// cannot be downloaded. Usage: node scripts/sql-from-schema.cjs > prisma/migrations/0001_init/migration.sql
const fs = require('node:fs');
const path = require('node:path');
const { get_dmmf } = require('@prisma/prisma-schema-wasm');

const schemaPath = path.join(__dirname, '..', 'prisma', 'schema.prisma');
const content = fs.readFileSync(schemaPath, 'utf8');
const { datamodel } = JSON.parse(get_dmmf(JSON.stringify({ prismaSchema: [[schemaPath, content]] })));
const enums = Object.fromEntries(datamodel.enums.map(e => [e.name, e.values.map(v => v.name)]));
const q = s => '`' + s + '`';

function colType(f) {
  if (f.kind === 'enum') return `ENUM(${enums[f.type].map(v => `'${v}'`).join(', ')})`;
  if (f.nativeType) {
    const [n, args] = f.nativeType;
    const map = { Text: 'TEXT', MediumText: 'MEDIUMTEXT', LongText: 'LONGTEXT', TinyText: 'TINYTEXT', VarChar: 'VARCHAR', Char: 'CHAR', UnsignedInt: 'INTEGER UNSIGNED', Date: 'DATE' };
    return (map[n] || n.toUpperCase()) + (args.length ? `(${args.join(',')})` : '');
  }
  return { String: 'VARCHAR(191)', Int: 'INTEGER', BigInt: 'BIGINT', Float: 'DOUBLE', Boolean: 'BOOLEAN', DateTime: 'DATETIME(3)', Json: 'JSON', Decimal: 'DECIMAL(65, 30)', Bytes: 'LONGBLOB' }[f.type];
}
function colDefault(f) {
  if (!f.hasDefaultValue || f.default === undefined) return '';
  const d = f.default;
  if (typeof d === 'object' && d !== null && d.name) {
    if (d.name === 'now') return ' DEFAULT CURRENT_TIMESTAMP(3)';
    if (d.name === 'autoincrement') return ' AUTO_INCREMENT';
    return ''; // uuid(), cuid() are generated by the client
  }
  if (typeof d === 'boolean') return ` DEFAULT ${d}`;
  if (typeof d === 'number') return ` DEFAULT ${d}`;
  if (f.kind === 'enum' || typeof d === 'string') return ` DEFAULT '${String(d).replace(/'/g, "''")}'`;
  return '';
}

const out = [];
const fks = [];
for (const m of datamodel.models) {
  const table = m.dbName || m.name;
  const lines = [];
  for (const f of m.fields.filter(f => f.kind !== 'object')) {
    lines.push(`    ${q(f.dbName || f.name)} ${colType(f)} ${f.isRequired ? 'NOT NULL' : 'NULL'}${colDefault(f)}`);
  }
  const idx = datamodel.indexes.filter(i => i.model === m.name);
  const extra = [];
  for (const i of idx.filter(i => i.type === 'unique')) {
    const cols = i.fields.map(x => x.name);
    extra.push(`    UNIQUE INDEX ${q(i.dbName || `${table}_${cols.join('_')}_key`)}(${cols.map(q).join(', ')})`);
  }
  for (const i of idx.filter(i => i.type === 'normal')) {
    const cols = i.fields.map(x => x.name);
    extra.push(`    INDEX ${q(i.dbName || `${table}_${cols.join('_')}_idx`)}(${cols.map(q).join(', ')})`);
  }
  const pk = idx.find(i => i.type === 'id');
  extra.push(`    PRIMARY KEY (${pk.fields.map(x => q(x.name)).join(', ')})`);
  out.push(`-- CreateTable\nCREATE TABLE ${q(table)} (\n${lines.join(',\n')},\n\n${extra.join(',\n')}\n) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n`);
  for (const f of m.fields.filter(f => f.kind === 'object' && f.relationFromFields && f.relationFromFields.length)) {
    const target = datamodel.models.find(x => x.name === f.type);
    const optional = f.relationFromFields.some(n => !m.fields.find(x => x.name === n).isRequired);
    const onDelete = f.relationOnDelete ? { Cascade: 'CASCADE', SetNull: 'SET NULL', Restrict: 'RESTRICT', NoAction: 'NO ACTION' }[f.relationOnDelete] : (optional ? 'SET NULL' : 'RESTRICT');
    fks.push(`-- AddForeignKey\nALTER TABLE ${q(table)} ADD CONSTRAINT ${q(`${table}_${f.relationFromFields.join('_')}_fkey`)} FOREIGN KEY (${f.relationFromFields.map(q).join(', ')}) REFERENCES ${q(target.dbName || target.name)}(${f.relationToFields.map(q).join(', ')}) ON DELETE ${onDelete} ON UPDATE CASCADE;\n`);
  }
}
process.stdout.write(out.join('\n') + '\n' + fks.join('\n'));
