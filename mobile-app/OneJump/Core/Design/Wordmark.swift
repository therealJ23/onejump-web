import SwiftUI

// The OneJump wordmark, drawn from the brand SVG so it stays sharp at any size
// and follows light and dark mode. Generated from wordmark.svg (viewBox 6262 × 1164).

/// Full wordmark: letters in the ink color and the jump arc in volt.
struct OneJumpWordmark: View {
    var height: CGFloat = 22
    @Environment(\.colorScheme) private var scheme

    var body: some View {
        let width = height * WordmarkGeometry.aspect
        ZStack {
            WordmarkLettersShape()
                .fill(scheme == .dark ? Color(hex: 0xE6ECE3) : Color(hex: 0x12281F))
            WordmarkArcShape()
                .stroke(arcColor, style: StrokeStyle(lineWidth: height * 58 / WordmarkGeometry.height, lineCap: .round))
            WordmarkArcDotsShape()
                .fill(arcColor)
        }
        .frame(width: width, height: height)
        .accessibilityElement()
        .accessibilityLabel("Onejump")
    }

    private var arcColor: Color { scheme == .dark ? Palette.volt : Color(hex: 0xA8CF1C) }
}

enum WordmarkGeometry {
    static let width: CGFloat = 6262
    static let height: CGFloat = 1164
    static let aspect: CGFloat = width / height

    /// Maps SVG units into the given rect, keeping the aspect ratio and centering.
    static func mapper(in rect: CGRect) -> (CGFloat, CGFloat) -> CGPoint {
        let scale = min(rect.width / width, rect.height / height)
        let originX = rect.minX + (rect.width - width * scale) / 2
        let originY = rect.minY + (rect.height - height * scale) / 2
        return { x, y in CGPoint(x: originX + x * scale, y: originY + y * scale) }
    }
}

struct WordmarkArcShape: Shape {
    func path(in rect: CGRect) -> Path {
        let p = WordmarkGeometry.mapper(in: rect)
        var path = Path()
        path.move(to: p(2404, 624))
        path.addCurve(to: p(3424, 624), control1: p(2832, -76), control2: p(2996, -76))
        return path
    }
}

struct WordmarkArcDotsShape: Shape {
    func path(in rect: CGRect) -> Path {
        let p = WordmarkGeometry.mapper(in: rect)
        let scale = min(rect.width / WordmarkGeometry.width, rect.height / WordmarkGeometry.height)
        let r: CGFloat = 55 * scale
        var path = Path()
        for center in [p(2404, 624), p(3424, 624)] {
            path.addEllipse(in: CGRect(x: center.x - r, y: center.y - r, width: r * 2, height: r * 2))
        }
        return path
    }
}

